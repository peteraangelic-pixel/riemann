"""Three-stage parameter sweep: hundreds of configs -> top 10 -> best of all.

The closed-loop tournament tests ONE candidate at a time. This script automates
the whole search over parameter configurations of an agent module:

  stage 1  SCREEN   every variant vs the baseline, few seeds, one big job pool
                     -> keep top_k by score rate (fast, rejects garbage cheaply)
  stage 2  PROMOTE  survivors vs the baseline, many seeds, Wilson gate each
                     -> keep only configs that statistically beat the baseline
  stage 3  FINALS   round-robin among the survivors (both seats), Bradley-Terry
                     strengths -> the single best config, pairwise honest

Variants are generated by regex-rewriting module-level constants of a base agent
file into agents/sweeps/ (gitignored). A config JSON lists explicit variants and
/or a "grid" (cartesian product). Example in sweeps/example_fert.json.

Output: results/sweep-<name>-<timestamp>.md (+ .json), committable like validate.

Examples:
    python scripts/sweep.py --config sweeps/example_fert.json
    python scripts/sweep.py --config sweeps/fert.json --stage screen --workers 16
"""
from __future__ import annotations

import argparse
import itertools
import json
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from kaggriculture_lab.stats import aggregate, bradley_terry, promotion_gate  # noqa: E402
from kaggriculture_lab.tournament import (  # noqa: E402
    _available_mem_gb, build_jobs, default_workers, run,
)

SWEEP_DIR = ROOT / "agents" / "sweeps"


# ---------------------------------------------------------------- variants ---
def make_variant(base: Path, name: str, params: dict) -> Path:
    """Rewrite module-level `NAME = ...` constants of base into a new agent file."""
    text = base.read_text(encoding="utf-8")
    for key, val in params.items():
        pat = re.compile(rf"^{re.escape(key)}\s*=.*$", re.MULTILINE)
        if not pat.search(text):
            avail = sorted(set(re.findall(r"^([A-Z_][A-Z0-9_]*)\s*=", text, re.MULTILINE)))
            raise SystemExit(f"[sweep] constant {key!r} not found in {base.name}. "
                             f"Available: {', '.join(avail)}")
        text = pat.sub(f"{key} = {val!r}", text, count=1)
    SWEEP_DIR.mkdir(parents=True, exist_ok=True)
    out = SWEEP_DIR / f"{name}.py"
    out.write_text(text, encoding="utf-8")
    return out


def expand_config(cfg: dict) -> list[dict]:
    """Explicit 'variants' plus cartesian product of 'grid'."""
    out = list(cfg.get("variants", []))
    grid = cfg.get("grid") or {}
    if grid:
        keys = list(grid)
        for i, combo in enumerate(itertools.product(*(grid[k] for k in keys))):
            params = dict(zip(keys, combo))
            out.append({"name": f"grid{i:03d}", "params": params})
    # de-duplicate by params, keep explicit names
    seen, uniq = set(), []
    for v in out:
        sig = json.dumps(v["params"], sort_keys=True)
        if sig in seen:
            continue
        seen.add(sig)
        uniq.append(v)
    return uniq


# ------------------------------------------------------------------ stages ---
def _agg_by_tag(rows: list[dict]) -> dict[str, object]:
    tags = sorted({r["tag"] for r in rows})
    return {t: aggregate([r for r in rows if r["tag"] == t]) for t in tags}


def stage_screen(variants: list[tuple[str, Path]], baseline: str,
                 games: int, seed: int, workers: int, lines: list) -> dict:
    jobs = []
    for name, path in variants:
        jobs += build_jobs(str(path), [baseline], games, seed,
                           swap_seats=True, steps=720, tag=name)
    lines.append(f"[1/3] SCREEN: {len(variants)} variants x {games} seeds x 2 seats "
                 f"= {len(jobs)} games ...")
    print(lines[-1])
    rows = run(jobs, workers, progress_every=max(50, len(jobs) // 5))
    aggs = _agg_by_tag(rows)
    ranked = sorted(aggs.items(),
                    key=lambda kv: (kv[1].score_rate, kv[1].mean_margin), reverse=True)
    lines.append("")
    lines.append(f"  {'variant':<22} {'W-L-T':>9} {'score%':>7} {'Wilson95':>13} "
                 f"{'margin':>8} {'err':>3}")
    for name, a in ranked:
        lines.append(f"  {name:<22} {f'{a.wins}-{a.losses}-{a.ties}':>9} "
                     f"{a.score_rate*100:7.1f} {f'{a.ci_low*100:.0f}-{a.ci_high*100:.0f}':>13} "
                     f"{a.mean_margin:+8.0f} {a.errors:3d}")
    lines.append("")
    return {name: a for name, a in ranked}


def stage_promote(survivors: list[tuple[str, Path]], baseline: str,
                  games: int, seed: int, workers: int, min_games: int,
                  lines: list) -> list[tuple[str, object, Path]]:
    jobs = []
    for name, path in survivors:
        jobs += build_jobs(str(path), [baseline], games, seed,
                           swap_seats=True, steps=720, tag=name)
    lines.append(f"[2/3] PROMOTE: {len(survivors)} variants x {games} seeds x 2 seats "
                 f"= {len(jobs)} games (Wilson gate vs baseline) ...")
    print(lines[-1])
    rows = run(jobs, workers, progress_every=max(50, len(jobs) // 4))
    aggs = _agg_by_tag(rows)
    lines.append("")
    passed = []
    lines.append(f"  {'variant':<22} {'W-L-T':>9} {'score%':>7} {'Wilson95':>13} "
                 f"{'margin':>8}  gate")
    for name, path in survivors:
        a = aggs[name]
        ok, reasons = promotion_gate(a, min_games=min_games)
        mark = "PASS" if ok else "fail"
        lines.append(f"  {name:<22} {f'{a.wins}-{a.losses}-{a.ties}':>9} "
                     f"{a.score_rate*100:7.1f} {f'{a.ci_low*100:.0f}-{a.ci_high*100:.0f}':>13} "
                     f"{a.mean_margin:+8.0f}  {mark}")
        if ok:
            passed.append((name, a, path))
    lines.append("")
    lines.append(f"  -> {len(passed)} variants passed the promotion gate")
    lines.append("")
    return passed


def stage_finals(finalists: list[tuple[str, Path]], games: int, seed: int,
                 workers: int, lines: list) -> dict:
    names = [n for n, _ in finalists]
    stem2name = {p.stem: n for n, p in finalists}  # opponent path stem -> tag
    jobs, wins, games_map = [], {}, {}
    for i, (na, pa) in enumerate(finalists):
        for nb, pb in finalists[i + 1:]:
            jobs += build_jobs(str(pa), [str(pb)], games, seed,
                               swap_seats=True, steps=720, tag=na)
    lines.append(f"[3/3] FINALS: round-robin of {len(names)} variants, "
                 f"{games} seeds x 2 seats per pair = {len(jobs)} games ...")
    print(lines[-1])
    rows = run(jobs, workers, progress_every=max(20, len(jobs) // 4))
    # rows are tagged with the FIRST-listed agent of each pair; opponent path
    # stem maps back to its tag. Accumulate from a's perspective, then mirror.
    for r in rows:
        a = r["tag"]
        b = stem2name.get(Path(str(r["opponent"])).stem, Path(str(r["opponent"])).stem)
        wins[(a, b)] = wins.get((a, b), 0.0) + (1.0 if r["outcome"] == "win"
                                                 else 0.5 if r["outcome"] == "tie" else 0.0)
        games_map[(a, b)] = games_map.get((a, b), 0) + 1
    # mirror: b's score = total - a's score (ties give 0.5 each -> sums to g)
    for (a, b), g in list(games_map.items()):
        games_map[(b, a)] = g
        wins[(b, a)] = g - wins.get((a, b), 0.0)
    bt = bradley_terry(wins, games_map, names)
    ranked = sorted(bt.items(), key=lambda kv: kv[1], reverse=True)
    lines.append("")
    lines.append("  Bradley-Terry strengths (geomean-normalized; >1 beats the field):")
    for name, strength in ranked:
        lines.append(f"    {name:<22} {strength:.3f}")
    lines.append("")
    # pairwise table (win % from the row agent's perspective)
    wname = 14
    lines.append("  pairwise win % (row vs column):")
    lines.append("  " + " " * wname + "".join(f"{n[:9]:>10}" for n in names))
    for n1 in names:
        cells = []
        for n2 in names:
            if n1 == n2:
                cells.append(f"{'--':>10}")
            else:
                g = games_map.get((n1, n2), 0)
                cells.append(f"{wins[(n1, n2)] / g * 100:9.0f}%" if g else f"{'--':>10}")
        lines.append(f"  {n1:<{wname}}" + "".join(cells))
    lines.append("")
    return {"bt": dict(bt), "ranked": [n for n, _ in ranked]}


# -------------------------------------------------------------------- main ---
def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", required=True)
    ap.add_argument("--stage", choices=["all", "screen", "promote", "finals"],
                    default="all")
    ap.add_argument("--workers", type=int, default=default_workers())
    ap.add_argument("--top-k", type=int, default=0, help="override config")
    ap.add_argument("--screen-games", type=int, default=0)
    ap.add_argument("--promote-games", type=int, default=0)
    args = ap.parse_args()

    mem_safe = max(1, int(_available_mem_gb() / 0.45))
    if args.workers > mem_safe:
        print(f"[note] --workers {args.workers} clamped to {mem_safe} (RAM)")
        args.workers = mem_safe

    cfg_path = Path(args.config)
    if not cfg_path.is_absolute():
        cfg_path = ROOT / cfg_path
    cfg = json.loads(cfg_path.read_text(encoding="utf-8"))
    base = (ROOT / cfg["base"]) if not Path(cfg["base"]).is_absolute() else Path(cfg["base"])
    baseline = cfg.get("baseline", "agents/ref/agent_v7.py")
    seed0 = cfg.get("start_seed", 20262000)
    screen_games = args.screen_games or cfg.get("screen_games", 10)
    promote_games = args.promote_games or cfg.get("promote_games", 100)
    final_games = cfg.get("final_games", promote_games)
    top_k = args.top_k or cfg.get("top_k", 10)

    t0 = time.perf_counter()
    lines = [f"# Sweep: {cfg.get('name', cfg_path.stem)}",
             f"base={base.name}  baseline={Path(baseline).name}  workers={args.workers}",
             f"screen={screen_games} seeds, promote={promote_games} seeds, "
             f"finals={final_games} seeds, top_k={top_k}", ""]

    specs = expand_config(cfg)
    variants = []
    lines.append(f"{len(specs)} configurations:")
    for v in specs:
        path = make_variant(base, v["name"], v["params"])
        variants.append((v["name"], path))
        lines.append(f"  {v['name']:<22} {json.dumps(v['params'], sort_keys=True)}")
    lines.append("")
    print("\n".join(lines[-len(specs) - 2:]))

    # always include the untouched base as a control variant
    ctrl = ("BASE_" + base.stem, base)
    if ctrl[0] not in [n for n, _ in variants]:
        variants.append(ctrl)

    result = {"config": cfg_path.name, "variants": [v[0] for v in variants]}

    screened = stage_screen(variants, baseline, screen_games, seed0,
                            args.workers, lines)
    result["screen"] = {n: a.to_dict() for n, a in screened.items()}
    if args.stage == "screen":
        ranked_names = [n for n, _ in sorted(screened.items(),
                       key=lambda kv: (kv[1].score_rate, kv[1].mean_margin), reverse=True)]
        result["screen_ranked"] = ranked_names
    else:
        top = [(n, dict(variants)[n]) for n, _ in
               sorted(screened.items(),
                      key=lambda kv: (kv[1].score_rate, kv[1].mean_margin),
                      reverse=True)[:top_k]]
        lines.append(f"  top {len(top)} advance: {', '.join(n for n, _ in top)}")
        lines.append("")
        promoted = stage_promote(top, baseline, promote_games, seed0 + 10000,
                                 args.workers, min_games=max(20, promote_games),
                                 lines=lines)
        result["promoted"] = [n for n, _, _ in promoted]
        if args.stage != "promote" and len(promoted) >= 2:
            finals = stage_finals([(n, p) for n, _, p in promoted], final_games,
                                  seed0 + 20000, args.workers, lines)
            result["finals"] = finals
            lines.append(f"  WINNER: {finals['ranked'][0]}")
        elif args.stage != "promote":
            lines.append("[3/3] FINALS skipped (need >=2 promoted variants)")

    lines.append("")
    lines.append(f"elapsed {time.perf_counter()-t0:.0f}s")

    results_dir = ROOT / "results"
    results_dir.mkdir(exist_ok=True)
    stamp = time.strftime("%Y%m%d-%H%M%S")
    name = cfg.get("name", cfg_path.stem)
    out_md = results_dir / f"sweep-{name}-{stamp}.md"
    out_md.write_text("\n".join(lines) + "\n", encoding="utf-8")
    (results_dir / f"sweep-{name}-{stamp}.json").write_text(
        json.dumps(result, indent=2, default=str), encoding="utf-8")
    print(f"\nWrote {out_md}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
